
numero23=float(input("Ingrese el primer número:"))
numero24=float(input("Ingrese el segundo número:"))

print("Suma:", numero23 + numero24)
print("Resta:", numero23 - numero24)
print("Multiplicación:", numero23 * numero24)
            
if numero24 != 0:
    print("División:", numero23 / numero24)
else:
    print("División: No se puede dividir entre cero")